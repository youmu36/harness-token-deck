class DomainError(Exception):
    def __init__(
        self,
        code: str,
        message: str,
        field: str | None = None,
        *,
        retryable: bool = False,
        conflict_revision: int | None = None,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.field = field
        self.retryable = retryable
        self.conflict_revision = conflict_revision
