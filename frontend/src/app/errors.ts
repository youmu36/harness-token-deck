export class AppError extends Error {
  constructor(readonly info: ErrorInfo) {
    super(errorMessage(info));
    this.name = 'AppError';
  }
  get code() { return this.info.code; }
}

export function errorMessage(error: ErrorInfo): string {
  const message = errorMessages[error.code] ?? error.message;
  return error.logId ? `${message}（日志编号 ${error.logId}）` : message;
}

export function asAppError(error: unknown): AppError {
  if (error instanceof AppError) return error;
  if (error instanceof Error && 'code' in error && typeof error.code === 'string') {
    return new AppError({ code: error.code, message: error.message, retryable: false });
  }
  return new AppError({ code: 'BRIDGE_UNAVAILABLE', message: '无法连接本机应用', retryable: true });
}

export function unwrap<T>(response: { ok: true; data: T } | { ok: false; error: ErrorInfo }): T {
  if (!response.ok) throw new AppError(response.error);
  return response.data;
}
