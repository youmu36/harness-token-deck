import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';

const destination = path.resolve(process.argv[2] ?? fileURLToPath(new URL('../frontend/src/infra/generated', import.meta.url)));
const schema = JSON.parse(await fs.readFile(path.join(destination, 'contracts.schema.json'), 'utf8'));
const banner = '// Generated by scripts/gen_contracts.py. Do not edit.\n';
const sections = schema.properties;
const commands = Object.keys(sections.requests.properties).sort();
const events = Object.keys(sections.events.properties).sort();
// Reuse validators for shared DTOs instead of inlining them into every response.
// The bridge reports a contract mismatch; retaining every nested error wastes memory.
const ajv = new Ajv({ strict: true, code: { source: true, esm: true }, inlineRefs: false, allErrors: false });
ajv.addSchema(schema);
const exports = {};
for (const [section, names] of [['requests', commands], ['responses', commands], ['events', events]]) {
  for (const [index, name] of names.entries()) {
    const id = `${schema.$id}#/properties/${section}/properties/${name}`;
    ajv.getSchema(id);
    exports[`${section}${index}`] = id;
  }
}
// ESM standalone code can refer to the CommonJS unicode-length helper.
const validators = standaloneCode(ajv, exports).replaceAll(
  'require("ajv/dist/runtime/ucs2length").default', '(value => Array.from(value).length)',
);
await fs.writeFile(path.join(destination, 'validators.js'),
  `${banner}${validators}\n`);
await fs.writeFile(path.join(destination, 'validators.d.ts'), banner +
  "import type { ValidateFunction } from 'ajv';\n" + Object.keys(exports)
    .map(name => `export declare const ${name}: ValidateFunction;`).join('\n') + '\n');
await fs.writeFile(path.join(destination, 'contracts.d.ts'), await compile(schema, 'Contracts', {
  bannerComment: banner.trim(), additionalProperties: false, unreachableDefinitions: true,
  maxItems: -1, style: { singleQuote: true, tabWidth: 2 },
}));
const table = (section, names) => names.map((name, index) => `  '${name}': validators.${section}${index},`).join('\n');
await fs.writeFile(path.join(destination, 'commands.ts'), `${banner}
import type { Contracts } from './contracts';
import * as validators from './validators.js';

export type CommandName = keyof Contracts['requests'];
export type RequestMap = Contracts['requests'];
export type ResponseMap = Contracts['responses'];
export type EventMap = Contracts['events'];
export type EventName = keyof EventMap;
export type CommandMap = { [K in CommandName]: { request: RequestMap[K]; response: ResponseMap[K] } };
export type Transport = (command: CommandName, payload: object) => Promise<unknown>;

export const requestValidators = {
${table('requests', commands)}
} as const;
export const responseValidators = {
${table('responses', commands)}
} as const;
export const eventValidators = {
${table('events', events)}
} as const;

export class ContractMismatch extends Error {
  readonly code = 'CONTRACT_MISMATCH';
  constructor(readonly command: CommandName) {
    super('响应与契约不一致：' + command);
    this.name = 'ContractMismatch';
  }
}

export function validateResponse<K extends CommandName>(command: K, value: unknown): ResponseMap[K] {
  if (!responseValidators[command](value)) throw new ContractMismatch(command);
  return value as ResponseMap[K];
}

export async function call<K extends CommandName>(
  transport: Transport, command: K, payload: RequestMap[K],
): Promise<ResponseMap[K]> {
  return validateResponse(command, await transport(command, payload));
}
`);
console.log(`Generated ${commands.length} commands and ${events.length} events`);
